"""Generates src/core/ColormapTables.inc from matplotlib (256 entries each).

Usage: python3 tools/generate_colormaps.py > src/core/ColormapTables.inc
"""

import matplotlib
import numpy as np

NAMES = [("gray", "gray"), ("viridis", "viridis"), ("inferno", "inferno"),
         ("magma", "magma"), ("plasma", "plasma"), ("cividis", "cividis"),
         ("turbo", "turbo"), ("hot", "hot"), ("jet", "jet"),
         ("coolwarm", "coolwarm"), ("seismic", "seismic")]

print("// Generated by tools/generate_colormaps.py from matplotlib "
      f"{matplotlib.__version__}. Do not edit.")
print("// 256 RGB entries per map, 0xRRGGBB.")
for display, name in NAMES:
    cmap = matplotlib.colormaps[name]
    rgb = (cmap(np.linspace(0.0, 1.0, 256))[:, :3] * 255.0 + 0.5).astype(int)
    words = [f"0x{r:02x}{g:02x}{b:02x}" for r, g, b in rgb]
    print(f'{{"{display}", {{')
    for i in range(0, 256, 8):
        print("    " + ", ".join(words[i:i + 8]) + ",")
    print("}},")
